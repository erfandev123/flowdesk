// Produce the dependency audit digest that ships with the release.
// Runs `npm audit` for both workspaces and writes the results to
// docs/DEPENDENCY-AUDIT.md
// Usage: node scripts/dependency-audit.js
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const NODE_PROJECT = path.join(__dirname, '..');
const ROOT = path.join(NODE_PROJECT, '..');
const OUT = path.join(ROOT, 'docs', 'DEPENDENCY-AUDIT.md');

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';

function audit(dir, args = []) {
  const res = spawnSync(npm, ['audit', '--json', ...args], {
    cwd: dir, encoding: 'utf8', shell: process.platform === 'win32',
  });
  let parsed = null;
  try {
    parsed = JSON.parse(res.stdout);
  } catch {
    // npm audit exits non-zero when vulnerabilities are found but still
    // prints valid JSON. If parsing fails there is nothing to report.
  }
  return parsed;
}

function summarise(auditResult) {
  if (!auditResult) return { total: 0, severity: {} };
  const meta = auditResult.metadata?.vulnerabilities ?? {};
  return {
    total: meta.total ?? 0,
    severity: {
      critical: meta.critical ?? 0,
      high: meta.high ?? 0,
      moderate: meta.moderate ?? 0,
      low: meta.low ?? 0,
    },
  };
}

const server = audit(path.join(NODE_PROJECT, 'server'), ['--omit=dev']);
const web = audit(path.join(NODE_PROJECT, 'web'));

const s = summarise(server);
const w = summarise(web);

function installedVersions(dir) {
  const res = spawnSync(npm, ['ls', '--depth=0', '--json'], {
    cwd: dir, encoding: 'utf8', shell: process.platform === 'win32',
  });
  try {
    const data = JSON.parse(res.stdout);
    const out = [];
    for (const [name, info] of Object.entries(data.dependencies ?? {})) {
      out.push(`| \`${name}\` | ${info.version} |`);
    }
    return out;
  } catch {
    return [];
  }
}

const serverVersions = installedVersions(path.join(NODE_PROJECT, 'server'));
const webVersions = installedVersions(path.join(NODE_PROJECT, 'web'));

const lines = [
  '# Dependency Audit',
  '',
  'Generated by `node scripts/dependency-audit.js`. Every dependency is pinned',
  'to an exact version in `package.json`, and both `package-lock.json` files are',
  'committed, so `npm ci` restores exactly these versions.',
  '',
  '## Result',
  '',
  '| Workspace | Critical | High | Moderate | Low | Total |',
  '|---|---|---|---|---|---|',
  `| server | ${s.severity.critical} | ${s.severity.high} | ${s.severity.moderate} | ${s.severity.low} | **${s.total}** |`,
  `| web | ${w.severity.critical} | ${w.severity.high} | ${w.severity.moderate} | ${w.severity.low} | **${w.total}** |`,
  '',
  '## Reproduce',
  '',
  '```bash',
  'cd "Node Project/server" && npm audit',
  'cd "Node Project/web"    && npm audit',
  '```',
  '',
  'Or both at once:',
  '',
  '```bash',
  'cd "Node Project"',
  'npm run audit',
  '```',
  '',
  '## Pinned versions — server',
  '',
  '| Package | Version |',
  '|---|---|',
  ...serverVersions,
  '',
  '## Pinned versions — web',
  '',
  '| Package | Version |',
  '|---|---|',
  ...webVersions,
  '',
  '## Why so few dependencies',
  '',
  'The runtime surface is deliberately tiny:',
  '',
  '- **Server** — `express` and `cookie-parser`. SQLite comes from Node itself,',
  '  so there is no database driver, no ORM and no native module to compile.',
  '- **Web** — React, React Router and the icon set. Charts are hand-written',
  '  SVG, so there is no charting library. Styling is Tailwind, which is a',
  '  build-time tool and ships nothing to the browser.',
  '',
  'Every version is pinned exactly, and the lockfiles are committed, so a',
  'reviewer restoring the packages gets the same build every time.',
  '',
];

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote docs/DEPENDENCY-AUDIT.md`);
console.log(`  server: ${s.total} vulnerabilities`);
console.log(`  web:    ${w.total} vulnerabilities`);
